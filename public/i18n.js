let currentLanguage = DEFAULT_LANGUAGE;

/** Returns a supported language without trusting arbitrary stored values. */
export function resolveLanguage(value) {
  return SUPPORTED_LANGUAGES.has(value) ? value : DEFAULT_LANGUAGE;
}

/** Formats a translated string using `{name}` placeholders. */
export function translate(key, variables = {}, language = currentLanguage) {
  const dictionary = translations[resolveLanguage(language)];
  const template = dictionary[key] ?? translations[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(variables[name] ?? `{${name}}`));
}

/** Allows automated tests to prove that every visible key exists in both languages. */
export function hasTranslation(key, language) {
  return Object.hasOwn(translations[resolveLanguage(language)], key);
}

export const t = (key, variables = {}) => translate(key, variables, currentLanguage);
export const getLanguage = () => currentLanguage;

/**
 * Applies translations to static markup and reloads after a language change so
 * all dynamic job cards, errors, and editor controls use one language.
 */
export function initializeI18n(root = document) {
  try {
    currentLanguage = resolveLanguage(localStorage.getItem(LANGUAGE_KEY));
  } catch {
    currentLanguage = DEFAULT_LANGUAGE;
  }
  root.documentElement.lang = currentLanguage;
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.setAttribute('placeholder', t(element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', t(element.dataset.i18nAria));
  });
  const selector = root.querySelector('#language-select');
  if (!selector) return;
  selector.value = currentLanguage;
  selector.setAttribute('aria-label', t('language.label'));
  selector.addEventListener('change', () => {
    const language = resolveLanguage(selector.value);
    try { localStorage.setItem(LANGUAGE_KEY, language); } catch {}
    window.location.reload();
  });
}

/** Keeps detailed Spanish API messages while preventing mixed-language English UI. */
export function apiError(body, fallbackKey) {
  if (currentLanguage === 'es' && typeof body?.error === 'string' && body.error.trim()) {
    return body.error;
  }
  return t(fallbackKey);
}

/** Translates the small set of persisted backend labels shown in the panel. */
export function localizeBackendLabel(value) {
  const labels = {
    recorte: t('quality.clip'),
    'recorte protegido': t('quality.protectedClip')
  };
  return labels[value] || value;
}
